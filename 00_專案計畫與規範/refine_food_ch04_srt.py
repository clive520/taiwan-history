def refine_text(text: str) -> str:
    # 1. OpenCC 全量臺灣繁體轉換 (包含慣用語)
    t = cc.convert(text)
    
    # 2. 清除連續重複出現的幻覺字符
    t = re.sub(r'(並且){2,}', '並且', t)
    t = re.sub(r'(帝){2,}', '代', t)
    t = re.sub(r'(肉臊){2,}', '肉臊', t)
    t = re.sub(r'(紅蔥頭){2,}', '紅蔥頭', t)
    t = re.sub(r'(蔭油){2,}', '蔭油', t)
    
    # 3. 歷史與名詞修正
    for pat, rep in REPLACEMENTS:
        t = re.sub(pat, rep, t)
        
    return t

def process_srt(srt_file: Path):
    if not srt_file.exists():
        print(f"⚠️ 檔案不存在：{srt_file}")
        return
        
    print(f"🔧 正在精修字幕：{srt_file.name}...")
    with open(srt_file, "r", encoding="utf-8") as f:
        content = f.read()
        
    lines = content.splitlines()
    new_lines = []
    
    for line in lines:
        if "-->" in line:
            new_lines.append(line)
        elif line.strip().isdigit():
            new_lines.append(line)
        elif not line.strip():
            new_lines.append(line)
        else:
            refined = refine_text(line)
            new_lines.append(refined)
            
    with open(srt_file, "w", encoding="utf-8") as f:
        f.write("\n".join(new_lines) + "\n")
        
    print(f"✅ 字幕精修完成：{srt_file.name}")

