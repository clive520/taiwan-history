def apply_corrections(text, corrections):
    for pat, rep in corrections:
        text = re.sub(pat, rep, text)
    return text

def format_timestamp(seconds):
    hours = int(seconds // 3600)
    minutes = int((seconds % 3600) // 60)
    secs = int(seconds % 60)
    millis = int(round((seconds - int(seconds)) * 1000))
    if millis >= 1000:
        secs += 1
        millis = 0
    return f"{hours:02d}:{minutes:02d}:{secs:02d},{millis:03d}"

def count_cjk(text):
    return len(re.findall(r'[\u4e00-\u9fff0-9a-zA-Z]', text))

def clean_punctuation(text):
    # 統一標點，移除結尾無意義標點
    t = text.strip()
    # 替換英文逗號為中文逗號
    t = re.sub(r',\s*', '，', t)
    # 移除行首標點
    t = re.sub(r'^[，。！？、；：,!?;:]+', '', t)
    # 移除行末句號或逗號（保持簡潔，問號與驚嘆號保留）
    t = re.sub(r'[，。、；;,\.]+$', '', t)
    return t

def process_segments_semantically(segments, corrections):
    """
    依據說話停頓、語法完整性與說話習慣合併/組織字幕
    """
    merged_subs = []
    cur = None
    
    for s in segments:
        raw_t = s.get('text', '').strip()
        if not raw_t:
            continue
            
        corr_t = apply_corrections(raw_t, corrections)
        t = clean_punctuation(corr_t)
        if not t:
            continue
            
        start = s['start']
        end = s['end']
        
        if cur is None:
            cur = {'start': start, 'end': end, 'text': t}
            continue
            
        gap = start - cur['end']
        cur_len = count_cjk(cur['text'])
        new_len = count_cjk(t)
        
        # 判斷是否合併
        # 1. 兩者相加 <= 22 字元（電視廣播標準安全行長）
        # 2. 中間幾乎無停頓 (gap < 0.35s)
        # 3. 任一側為短碎片 (<= 4 字，例如「嘉義」、「劉永福」、「溺水」、「6」)
        #    或者 兩句非常短 (總長 <= 16 字且 gap < 0.25s)
        # 4. 當前句末尾不是強終止標點（問號或驚嘆號）
        should_merge = False
        if cur_len + new_len <= 22:
            no_strong_end = not cur['text'].endswith(('？', '！', '?', '!'))
            if no_strong_end:
                if (cur_len <= 4 or new_len <= 4) and gap < 0.40:
                    should_merge = True
                elif (cur_len + new_len <= 16) and gap < 0.25:
                    should_merge = True
                    
        if should_merge:
            # 合併，若沒有標點則視語意加上適當逗號或微空格
            if not cur['text'][-1] in '，、：:':
                sep = '，' if cur_len >= 6 and new_len >= 5 else ' '
            else:
                sep = ''
            cur['text'] = clean_punctuation(cur['text'] + sep + t)
            cur['end'] = end
        else:
            merged_subs.append(cur)
            cur = {'start': start, 'end': end, 'text': t}
            
    if cur:
        merged_subs.append(cur)
        
    # 時間戳防重疊修正
    for i in range(len(merged_subs) - 1):
        if merged_subs[i]['end'] > merged_subs[i+1]['start']:
            merged_subs[i]['end'] = merged_subs[i+1]['start']
            
    return merged_subs

def build_srt_from_json(json_path, srt_path, corrections):
    with open(json_path, 'r', encoding='utf-8') as f:
        d = json.load(f)
        
    segs = d.get('segments', [])
    if not segs:
        print(f"[ERROR] {json_path} 無 segments 資料！")
        return False
        
    subs = process_segments_semantically(segs, corrections)
    
    with open(srt_path, 'w', encoding='utf-8') as f:
        for idx, sub in enumerate(subs, 1):
            s_str = format_timestamp(sub['start'])
            e_str = format_timestamp(sub['end'])
            f.write(f"{idx}\n{s_str} --> {e_str}\n{sub['text']}\n\n")
            
    lens = [count_cjk(s['text']) for s in subs]
    avg_l = sum(lens) / len(lens) if lens else 0
    max_l = max(lens) if lens else 0
    print(f"✅ [SRT 生成完成] {Path(srt_path).name}: 共 {len(subs)} 行 (平均 {avg_l:.1f} 字, 最大 {max_l} 字)")
    return True

